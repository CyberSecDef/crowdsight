"""Phase 6 Step 6 — the release gate.

Everything here is `integration`-marked and excluded from the fast suite, and
the spec is explicit that it is required before any release. Two tests, at two
scales:

**The micro-run.** Three agents, two rounds, real local inference — exactly what
the spec asks for. It proves the chain the whole project rests on: the local
model binding answers, OASIS builds a population from the files Phase 4 writes,
the broadcaster seeds the event, agents take real turns, and Step 3's round
bookkeeping attributes what they did.

**The pipeline.** `create` → `prepare` → `start` → complete through the service
layer, with a population generated by the model rather than handed in. Slower,
and worth it: driving this by hand is what found the event-loop deadlock in
Step 5, and a bug that only appears when the pieces are assembled is exactly
the kind a smoke test exists to catch.

Both use short temporary paths: the control socket is limited to 107
characters and pytest's own `tmp_path` can exhaust that on its own.
"""

