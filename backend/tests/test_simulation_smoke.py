@pytest.fixture
def workspace():
    """A short-pathed working directory, removed however the test ends."""
    directory = Path(tempfile.mkdtemp(prefix="cs-smoke-", dir="/tmp"))
    yield directory
    shutil.rmtree(directory, ignore_errors=True)


def read_db(path):
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row
    try:
        return {
            "users": connection.execute(
                "SELECT user_id, user_name FROM user").fetchall(),
            "posts": connection.execute(
                "SELECT post_id, user_id, content FROM post").fetchall(),
            "traces": connection.execute("SELECT action FROM trace").fetchall(),
        }
    finally:
        connection.close()


