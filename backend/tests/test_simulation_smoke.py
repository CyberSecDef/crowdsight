async def test_three_agents_two_rounds_against_local_ollama(integration_config,
                                                             workspace):
    """The chain the whole project rests on, end to end and unmocked."""
    profiles = workspace / "profiles"
    write_profiles(PEOPLE, profiles, default_country="United Kingdom")

    config = SimulationConfig.model_validate(SCENARIO)
    config.scheduled_events[0].enabled = True  # an operator turned it on at review

    database = workspace / "simulation.db"
    ledger = RunLedger(database)
    runner = SimulationRunner(config, profiles, database,
                              config=integration_config, rng_seed=5)
    summaries = []
    try:
        await runner.setup()

        assert len(runner.population()) == 3, "three agents"
        assert runner.broadcaster is not None, "and an account to seed the event"
        assert runner.env.llm_semaphore._value == integration_config.LLM_CONCURRENCY

        ledger.ensure_schema()
        marks = ledger.marks()
        summaries.append(await runner.seed())
        ledger.record_round(_record(0, summaries[-1], ledger, marks))

        for index in (1, 2):
            marks = ledger.marks()
            summaries.append(await runner.run_round(index))
            ledger.record_round(_record(index, summaries[-1], ledger, marks))
    finally:
        await runner.close()

    # -- the run itself ----------------------------------------------------
    assert len(summaries) == 3, "a seed round and two simulated rounds"
    assert summaries[2].events_fired == 1, "the enabled event fired in its round"
    assert summaries[1].events_fired == 0, "and not before"
    assert sum(s.invoked for s in summaries[1:]) > 0, "agents took real turns"
    assert sum(s.failed for s in summaries) == 0, \
        f"agent turns failed: {[s.failures for s in summaries]}"

    # -- what it produced --------------------------------------------------
    data = read_db(database)
    assert len(data["users"]) == 4, "three agents plus the broadcaster"
    assert all(row["user_name"] for row in data["users"]), \
        "OASIS signs population agents up as NULL without our backfill"
    contents = [row["content"] or "" for row in data["posts"]]
    assert any("density policy" in text for text in contents), "the seed post"
    assert any("too timid" in text for text in contents), "the scheduled event"
    assert len(data["posts"]) > 2, "agents posted of their own accord"
    assert data["traces"], "actions were traced"

    # -- and that it can be described afterwards ---------------------------
    rounds = ledger.rounds()
    assert [r.round for r in rounds] == [0, 1, 2]
    assert any(r.action_counts for r in rounds), "per-action counts were recorded"

    by_round = ledger.posts_by_round()
    assert len(by_round[0]) >= 1, "the seed post is attributed to round zero"
    assert sum(len(ids) for ids in by_round.values()) == len(data["posts"]), \
        "every post belongs to exactly one round"

    progress = ledger.progress(total_rounds=2)
    assert progress["total_rounds"] == 2
    assert progress["action_counts"], "the run can report what the population did"


def _record(index, summary, ledger, marks_before):
    from app.services.simulation_persistence import RoundRecord

    return RoundRecord(
        round=index, invoked=summary.invoked, acted=summary.acted,
        failed=summary.failed, skipped=summary.skipped,
        events_fired=summary.events_fired,
        action_counts=ledger.action_counts(marks_before),
        failures=summary.failures,
    )


