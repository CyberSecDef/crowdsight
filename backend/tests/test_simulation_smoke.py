async def test_create_prepare_start_completes_a_run(integration_config, workspace,
                                                     monkeypatch):
    """`create` → `prepare` → `start` → complete, with a model-built population.

    Slower than the micro-run and deliberately kept: assembling these pieces is
    what exposed the event-loop deadlock, and no unit test saw it.
    """
    from app.services.population import plan_population, sketch_population
    from app.services.profile_generator import EntityContext, ProfileGenerator
    from app.services.profile_job import generate_population
    from app.utils.llm_client import LLMClient

    settings = integration_config.model_copy(update={
        "MAX_CONCURRENT_SIMULATIONS": 2, "API_LLM_RESERVE": 1})
    store = SimulationStore(workspace / "simulations")
    manager = SimulationManager(store, config=settings)

    # ---- create ----------------------------------------------------------
    meta = store.create_pending(graph_id="smoke", platform="twitter", rounds=2,
                                total_agents=3)
    assert store.load_meta(meta.sim_id).state == SimulationState.DRAFT
    assert not store.prepared(meta.sim_id)

    # ---- prepare: a real population from the real model -------------------
    document = (
        "Riverbend City Council published a draft housing density policy on 14 "
        "March. Councillor Jane Doe, who chairs the Planning Committee, said the "
        "proposal would permit four-storey development along the Eastgate "
        "corridor. The Riverbend Residents Association objected that the "
        "twenty-one day consultation was inadequate."
    )
    llm = LLMClient(settings)
    try:
        sketch = await sketch_population(None, document, llm)
        generator = ProfileGenerator(settings, llm=llm)
        contexts = [EntityContext(uuid="e-1", name="Councillor Jane Doe",
                                  type="Person")]
        plan = plan_population(contexts, total=3, sketch=sketch,
                               generator=generator, named_ratio=0.34)

        seen: list[tuple[int, int]] = []
        result = await generate_population(
            generator, plan, store.profiles_dir(meta.sim_id),
            progress=lambda done, total, name: seen.append((done, total)))
        assert result.profiles, "the model produced no personas"
        assert seen and seen[-1][0] == seen[-1][1], "progress reached completion"

        bundle = write_profiles(result.profiles, store.profiles_dir(meta.sim_id))
        assert bundle.count == len(result.profiles)

        config = SimulationConfig.model_validate({**SCENARIO, "graph_id": "smoke"})
        store.save_config(meta.sim_id, config)
    finally:
        await llm.aclose()

    assert store.prepared(meta.sim_id)
    assert store.load_meta(meta.sim_id).state == SimulationState.DRAFT, \
        "preparing must not lock the configuration"

    # ---- start: a real process, supervised over its socket ----------------
    record = manager.start(meta.sim_id)
    assert record.pid > 0
    assert record.concurrency >= 1, "the worker was given a share of the budget"
    assert store.load_meta(meta.sim_id).state == SimulationState.RUNNING

    stages: list[str] = []
    deadline = time.time() + 900
    while time.time() < deadline:
        status = manager.status(meta.sim_id)
        if status.get("stage"):
            stages.append(status["stage"])
        if not status.get("running"):
            break
        time.sleep(1.0)

    assert stages, "no status ever came back from the worker"
    assert store.load_meta(meta.sim_id).state == SimulationState.COMPLETE, \
        f"run did not complete; stages seen: {stages}"

    # ---- what the run left behind ----------------------------------------
    ledger = RunLedger(store.sim_dir(meta.sim_id) / "simulation.db")
    assert [r.round for r in ledger.rounds()] == [0, 1, 2]

    data = read_db(store.sim_dir(meta.sim_id) / "simulation.db")
    assert len(data["users"]) == len(result.profiles) + 1, "population plus broadcaster"
    assert data["posts"], "nothing was posted"

    assert manager.capacity() == settings.MAX_CONCURRENT_SIMULATIONS, \
        "the slot was returned when the run finished"
    assert not (store.sim_dir(meta.sim_id) / "control.sock").exists(), \
        "the control socket was left behind"
